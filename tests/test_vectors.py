"""
Published test vectors for the primitives this protocol is built from.

Why this file exists
--------------------
``tests/test_primitives.py`` cross-validates against ``cryptography``, a second
implementation of the same standards. That catches disagreement between two
implementations, but it cannot catch a case where **both** are wrong the same
way, and it says nothing about conformance to a specification. Published
vectors do: they are a fixed external reference, so passing means agreeing with
the standard rather than with a sibling library.

What is *not* here, and why
---------------------------
There are no Signal test vectors for X3DH or the Double Ratchet, because Signal
does not publish any. Both specification documents were checked:

- X3DH, revision 1 (2016-11-04), https://signal.org/docs/specifications/x3dh/
- The Double Ratchet Algorithm, revision 4 (2025-11-04),
  https://signal.org/docs/specifications/doubleratchet/

Neither has a test-vectors appendix; both end at References. The composed
protocols therefore still rely on the cross-validation in
``tests/test_primitives.py`` and on round-trip tests, and that limitation is
real. The closest thing to an external reference for the compositions is the
pair of intermediate values asserted in
``TestComposedProtocolsBoundToThePrimitives`` below, which pins the X3DH root
key and the first ratchet step to the primitives checked here. It is a
self-consistency anchor, not a conformance claim.

Provenance of every constant below is the RFC section named in its comment.
Nothing in this file is generated by this implementation, and a failing
assertion means a transcription error or a real defect -- never a value to be
regenerated to make the suite green.
"""

import nacl.bindings
import pytest
from nacl.exceptions import BadSignatureError
from nacl.signing import SigningKey, VerifyKey

from src.crypto.kdf import expand, extract, hkdf
from src.crypto.key_management import (
    identity_private_x25519,
    identity_public_x25519,
)


def h(text: str) -> bytes:
    """Hex, tolerating the whitespace the RFCs use to group their output."""
    return bytes.fromhex(''.join(text.split()))


