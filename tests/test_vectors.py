#
# The values below are part of the wire and session contract, not internal
# tuning. They are pinned as literals on purpose: deriving the expected value
# from the module under test would make the assertion true for any edit, which
# is how a change to the HKDF info string can pass every test while breaking
# every stored session.
#
# PROTOCOL_VERSION exists precisely because these strings changed once already.
# The v2 bump came with a different KDF_CK and a different HKDF info string, and
# sessions written before it are refused on load. Changing one of these without
# bumping the version reintroduces the exact failure the version check was added
# to prevent: sessions that load cleanly and then silently fail to decrypt.

class TestProtocolConstantsArePinned:
    def test_ratchet_hkdf_info(self):
        from src.crypto.double_ratchet import HKDF_INFO
        assert HKDF_INFO == b'WhisperRatchet-v2'

    def test_ratchet_protocol_version(self):
        from src.crypto.double_ratchet import PROTOCOL_VERSION
        assert PROTOCOL_VERSION == 2

    def test_x3dh_context(self):
        """
        Mixed in as the HKDF info for the X3DH root key.

        The specification leaves info empty. A non-empty context is deliberate
        domain separation and is a documented deviation, but it is also a
        constant both sides must agree on.
        """
        from src.crypto.x3dh import DEFAULT_CONTEXT
        assert DEFAULT_CONTEXT == b'DecentralizedMessenger-X3DH-v1'

    def test_x3dh_domain_separator_prefix(self):
        """
        F = 0xFF * 32 for 256-bit curves, X3DH section 4.

        This is specified, not chosen, so it is a conformance value.
        """
        from src.crypto.x3dh import X25519_F
        assert X25519_F == b'\xff' * 32

    def test_initiator_transcript_label(self):
        from src.crypto.x3dh import INIT_TRANSCRIPT_LABEL
        assert INIT_TRANSCRIPT_LABEL == b'X3DH-init-v1'

    def test_key_confirmation_info(self):
        from src.crypto.x3dh import KEY_CONFIRMATION_INFO
        assert KEY_CONFIRMATION_INFO == b'WhisperKeyConfirmation'

    def test_x3dh_default_context_is_used_when_none_is_given(self):
        """
        The previous test pins the string; this pins that it is the default.

        A caller that omits the context and one that passes it explicitly must
        derive the same root key, or two code paths silently produce different
        sessions.
        """
        from src.crypto.x3dh import DEFAULT_CONTEXT, X3DH

        parts = [RFC5869_CASE_1['prk']] * 4
        assert (
            X3DH.derive_master_key(parts)
            == X3DH.derive_master_key(parts, context=DEFAULT_CONTEXT)
        )
        assert (
            X3DH.derive_master_key(parts)
            != X3DH.derive_master_key(parts, context=b'something else')
        )


#: Outputs from the RFC 7748 vectors, reused above as arbitrary 32-byte secrets.
