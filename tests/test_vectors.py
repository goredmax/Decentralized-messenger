# RFC 7748, section 5.2 -- X25519
# ---------------------------------------------------------------------------
#
# Every DH in X3DH and in both ratchets is X25519, so this is the vector that
# covers the primitive the whole protocol's forward secrecy rests on.

#: 5.2, X25519, first vector.
RFC7748_X25519_1 = (
    'a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4',
    'e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c',
    'c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552',
)

#: 5.2, X25519, second vector.
RFC7748_X25519_2 = (
    '4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d',
    'e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493',
    '95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957',
)

#: 5.2, the iterated form: k and u both start at 09 followed by 31 zero bytes,
#: and each iteration sets k to f(k) and u to the old k.
RFC7748_ITERATED_SEED = h('09' + '00' * 31)
RFC7748_ITERATED_1 = h(
    '422c8e7a6227d7bca1350b3e2bb7279f7897b87bb6854b783c60e80311ae3079'
)
RFC7748_ITERATED_1000 = h(
    '684cf59ba83309552800ef566f2f4d3c1c3887c49360e3875f2eb94d99532c51'
)
RFC7748_ITERATED_1000000 = h(
    '7c3911e0ab2586fd864497297e575e6f3bc601c0883c30df5f4dd2d24f665424'
)


def _x25519(scalar: bytes, u_coordinate: bytes) -> bytes:
    """
    The bare RFC 7748 function, with no low-order rejection.

    Deliberately ``crypto_scalarmult`` directly rather than the project's
    ``_dh``, because the wrappers add an all-zero check that these vectors do
    not exercise. This checks the primitive; the wrapper's rejection behaviour
    is checked in test_double_ratchet.py and test_x3dh.py.
    """
    return nacl.bindings.crypto_scalarmult(scalar, u_coordinate)


class TestX25519Rfc7748:
    @pytest.mark.parametrize('vector', [RFC7748_X25519_1, RFC7748_X25519_2],
                             ids=['first', 'second'])
    def test_scalarmult_matches_the_rfc(self, vector):
        scalar, u_coordinate, expected = (h(part) for part in vector)
        assert _x25519(scalar, u_coordinate) == expected

    @pytest.mark.parametrize('iterations, expected', [
        (1, RFC7748_ITERATED_1),
        (1000, RFC7748_ITERATED_1000),
    ], ids=['1-iteration', '1000-iterations'])
    def test_iterated_matches_the_rfc(self, iterations, expected):
        """
        The iterated vectors catch a wrong clamping or a non-X25519 ladder.

        A single-shot vector can pass with an implementation that is subtly
        wrong in a way only repetition exposes. The 1,000,000-iteration vector
        is omitted deliberately: it costs minutes of CI time to re-derive a
        property the 1,000-iteration case already covers.
        """
        k = u_coordinate = RFC7748_ITERATED_SEED
        for _ in range(iterations):
            k, u_coordinate = _x25519(k, u_coordinate), k
        assert k == expected

    def test_diffie_hellman_is_symmetric(self):
        """
        Both parties must reach the same secret.

        The symmetry is ``f(a, base(b)) == f(b, base(a))`` -- the two inputs
        are a private scalar and the *other* party's public key. It is not
        ``f(a, b) == f(b, a)``: swapping the arguments of a single call is a
        different computation, not a reordered one, and libsodium is right to
        return different values for it.

        X3DH and both ratchets rely on this in every DH they perform, and a
        backend that broke it would pass the one-shot vectors above, which only
        ever check one direction.
        """
        secret_a = h(RFC7748_X25519_1[0])
        secret_b = h(RFC7748_X25519_2[0])

        public_b = nacl.bindings.crypto_scalarmult_base(secret_b)
        public_a = nacl.bindings.crypto_scalarmult_base(secret_a)

        assert _x25519(secret_a, public_b) == _x25519(secret_b, public_a)

    def test_the_million_iteration_value_is_recorded(self):
        """
        The vector is kept in the file even though it is not run.

        Deleting it would lose the reference; keeping it documents the choice
        above. Guarded on the value so an accidental edit is caught.
        """
        assert RFC7748_ITERATED_1000000.hex().startswith('7c3911e0ab2586fd')
        assert len(RFC7748_ITERATED_1000000) == 32


